class CommandMatcher:
    """Загружает синонимы (дефолт + пользовательские), строит индексы, матчит фразы."""

    def __init__(self, default_synonyms=None, synonyms_file=SYNONYMS_FILE):
        self.default = default_synonyms or DEFAULT_SYNONYMS
        self.file = synonyms_file
        self.synonyms = {}
        self.exact = {}
        self.phrase_index = []
        self.rebuild()

    # ── хранение ──
    def load_user(self):
        if os.path.exists(self.file):
            try:
                with open(self.file, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception as e:
                print(f"⚠️ Ошибка чтения {self.file}: {e}")
        return {}

    def save_user(self, user):
        os.makedirs(os.path.dirname(self.file), exist_ok=True)
        with open(self.file, "w", encoding="utf-8") as f:
            json.dump(user, f, ensure_ascii=False, indent=2)

    def rebuild(self):
        merged = {k: [norm(p) for p in v] for k, v in self.default.items()}
        for k, phrases in self.load_user().items():
            if isinstance(phrases, list):
                clean = [norm(p) for p in phrases if str(p).strip()]
                if clean:
                    merged[k] = clean
        self.synonyms = merged
        self.exact = {}
        for k, ps in merged.items():
            for p in ps:
                self.exact[p] = k
        self.phrase_index = sorted(((p, k) for k, ps in merged.items() for p in ps), key=lambda x: -len(x[0]))

    # ── редактирование ──
    def set_synonyms(self, key, phrases):
        user = self.load_user()
        user[key] = [norm(p) for p in phrases if str(p).strip()]
        self.save_user(user)
        self.rebuild()

    def add_synonym(self, key, phrase):
        base = list(self.synonyms.get(key, self.default.get(key, [])))
        p = norm(phrase)
        if p and p not in base:
            base.append(p)
        self.set_synonyms(key, base)

    def reset_synonyms(self, key):
        user = self.load_user()
        user.pop(key, None)
        self.save_user(user)
        self.rebuild()

    def all_keys(self):
        return sorted(set(list(self.default.keys()) + list(self.synonyms.keys())))

    # ── обучение голосом: «научи команду громче говорить сильнее звук» ──
    # Разделители: «=», «—», «это», «означает», «как», «говорить», «произносить», «произносится как».
    _LEARN_SEP = r"(?:=|—|-| это | означает | как | говорить | произносить | произносится как )"
    # варианты слов «команда/фраза/синоним» в любом падеже перед названием команды
    _LEARN_NOUN = r"(?:(?:команду|команды|команда|фразу|фразы|фраза|синониму|синонимом|синоним)\s+)?"
    LEARN_RE = re.compile(
        r"^(?:научи(?: меня)?|запомни(?: нас)?|добавь(?: мой)?|выучи)"
        r"\s+" + _LEARN_NOUN + r"(?!что )«?(?P<cmd>.+?)»?\s*" + _LEARN_SEP + r"+(?P<syn>.+)$")

    # обратный порядок: «добавь синоним шепчи к команде тише»
    LEARN_REV_RE = re.compile(
        r"^(?:добавь|научи|выучи)(?: меня)?\s+синоним(?:ом)?\s+«?(?P<syn>.+?)»?\s+"
        r"(?:к|для)\s+(?:команду|команды|команда|фразу|фраза)?\s*«?(?P<cmd>.+?)»?\s*$")

    def label_of(self, key):
        """Человеческая метка действия для ответов («Громче» вместо vol_up)."""
        try:
            from .actions import ACTIONS
            if key in ACTIONS:
                return ACTIONS[key][0]
        except Exception:
            pass
        return key

    def try_learn(self, text):
        t = norm(text)
        m2 = self.LEARN_REV_RE.match(t)
        m = self.LEARN_RE.match(t)
        # если обе формы матчатся — берём ту, где часть команды распознаётся
        cmd_part = syn = None
        for mo, rev in ((m2, True), (m, False)):
            if not mo:
                continue
            c = re.sub(r"(?:^|\s)(?:команду|команда|фразу|фраза|синонимом|синоним)\s+", " ",
                       norm(mo.group("cmd"))).strip()
            s = mo.group("syn").strip(" «»\"'")
            if rev and (self.find_key_by_label_or_id(c) or self.fuzzy_key(c)):
                cmd_part, syn = c, s
                break
            if not rev:
                cmd_part, syn = c, s
                break
            if cmd_part is None:
                cmd_part, syn = c, s
        if cmd_part is None:
            return None
        cmd_part = re.sub(r"(?:^|\s)(?:команду|команда|фразу|фраза|синонимом|синоним)\s+", " ", cmd_part).strip()
        key = self.find_key_by_label_or_id(cmd_part)
        if not key:
            key = self.fuzzy_key(cmd_part)
        if not key:
            return {"ok": False, "msg": f"Не знаю команду «{cmd_part}». Скажите список команд."}
        self.add_synonym(key, syn)
        label = self.label_of(key)
        return {"ok": True, "key": key, "syn": syn,
                "msg": f"Выучил: «{syn}» теперь означает команду «{label}»."}

    def find_key_by_label_or_id(self, text):
        """Ищет команду по id («vol_up») или по человеческой метке/синониму («громче»)."""
        t = norm(text)
        if t in self.default:
            return t
        # точное совпадение с синонимом любой команды — пользователь называет команду её же фразой
        if t in self.exact:
            return self.exact[t]
        # совпадение с меткой действия («Громче» → vol_up)
        try:
            from .actions import ACTIONS
            for k, v in ACTIONS.items():
                if norm(v[0]) == t:
                    return k
        except Exception:
            pass
        for k in self.all_keys():
            if norm(k) == t:
                return k
        return None

    def fuzzy_key(self, text):
        if not _fuzz_process:
            return None
        keys = self.all_keys()
        match, score = _fuzz_process.extractOne(norm(text), keys)
        return match if score >= 80 else None

    # ── распознавание ──
    def match(self, text, conservative=False):
        """Возвращает (key, payload_text) или None.
        Точное совпадение — всегда выигрывает; частичное/фuzzy — только если фраза длиннее 2 слов
        и не является короткой системной командой (иначе «да», «нет», «ю туб» ломали бы диалог).
        conservative=True — строгий режим для основного цикла ассистента: отключает fuzzy-подстановку,
        чтобы обычный диалог с ИИ никогда не превращался в случайно выполненную команду."""
        t = norm(text)
        if not t:
            return None
        # 1. точное совпадение
        if t in self.exact:
            return (self.exact[t], t)
        words = t.split()
        # 2. глагол открытия: «открой обс» → «обс» (для кастомных команд см. custom.py)
        stripped = t
        opened = False
        for v in OPEN_VERBS:
            if stripped.startswith(v):
                stripped = stripped[len(v):].strip()
                opened = True
                break
        if stripped in self.exact and (opened or len(words) > 2):
            return (self.exact[stripped], stripped)
        # 3. триггеры поиска (только с реальным запросом)
        for trig in SEARCH_TRIGGERS:
            if t.startswith(trig):
                query = t[len(trig):].strip()
                if not query:
                    continue
                if any(tr2 != trig and tr2.startswith(trig) and tr2[len(trig):].startswith(query)
                       for tr2 in SEARCH_TRIGGERS):
                    continue
                return ("__websearch", query)
        # 4. фраза внутри команды (длинные фразы, команда из нескольких слов)
        if len(words) >= 3:
            for phrase, key in self.phrase_index:
                if len(phrase) >= 8 and phrase in t:
                    return (key, t)
        # 5. «громкость 50» / «яркость 70»
        for pattern, key in SET_PATTERNS:
            m = pattern.search(t)
            if m:
                return (key, t)
        # 6. fuzzy — последний шанс (только для развёрнутых фраз, не в строгом режиме)
        if not conservative and _fuzz_process and self.exact and len(words) >= 3:
            match, score = _fuzz_process.extractOne(t, list(self.exact.keys()))
            if score >= 88:
                return (self.exact[match], t)
        return None
